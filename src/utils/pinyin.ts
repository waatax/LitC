export function getPinyin(text: string): string | undefined {
  if (!text) return undefined
  if (SENTENCE_PINYIN_MAP[text]) return SENTENCE_PINYIN_MAP[text]

  // Character-by-character automatic fallback
  const chars = Array.from(text)
  const pyTokens: string[] = []
  let foundAny = false

  for (const ch of chars) {
    if (CHAR_MAP[ch]) {
      pyTokens.push(CHAR_MAP[ch].py)
      foundAny = true
    } else if (/[\p{P}\s]/u.test(ch)) {
      pyTokens.push(ch)
    } else {
      pyTokens.push('')
    }
  }

  return foundAny ? pyTokens.join(' ').replace(/\s+([，。！？；：、「」『』])/g, '$1').trim() : undefined
}

