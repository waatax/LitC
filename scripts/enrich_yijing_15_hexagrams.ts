function enrichYijing() {
  const file = path.resolve(__dirname, '../src/data/work_chunks/yi-jing.ts')
  const bundle = loadBundle(file)

  let count = 0
  for (const p of bundle.passages) {
    if (YIJING_ENRICHED[p.id]) {
      p.readingAid.analysis = YIJING_ENRICHED[p.id]
      count++
    }
  }

  saveBundle(file, bundle)
  console.log(`✅ Successfully enriched ${count} Yi Jing hexagram analyses!`)
}

