// Helper to rebuild sentences for a passage so canonicalText equals joined sentences
function rebuildSentencesForPassage(p, newCanonical) {
  p.canonicalText = newCanonical
  const rawClauses = newCanonical.split(/(?<=[。！？；\n])/).map((s) => s.trim()).filter(Boolean)
  const existingSentences = p.sentenceIds.map((sid) => bundle.sentences.find((s) => s.id === sid)).filter(Boolean)

  if (rawClauses.length === existingSentences.length) {
    rawClauses.forEach((c, idx) => {
      existingSentences[idx].canonicalText = c
    })
  } else {
    const baseId = p.id
    const newSentenceIds = []
    bundle.sentences = bundle.sentences.filter((s) => !p.sentenceIds.includes(s.id))
    rawClauses.forEach((c, idx) => {
      const sid = `${baseId}_s-${idx + 1}`
      newSentenceIds.push(sid)
      bundle.sentences.push({
        id: sid,
        workId: p.workId,
        chapterId: p.chapterId,
        passageId: p.id,
        order: idx + 1,
        canonicalText: c,
        chunks: [],
      })
    })
    p.sentenceIds = newSentenceIds
  }
}

