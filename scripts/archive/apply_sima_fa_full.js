function getNewIds(origIdx) {
  let chNum = 1;
  let pNum = origIdx + 1;
  if (origIdx >= 15 && origIdx < 25) {
    chNum = 2;
    pNum = origIdx - 15 + 1;
  } else if (origIdx >= 25 && origIdx < 40) {
    chNum = 3;
    pNum = origIdx - 25 + 1;
  } else if (origIdx >= 40 && origIdx < 60) {
    chNum = 4;
    pNum = origIdx - 40 + 1;
  } else if (origIdx >= 60) {
    chNum = 5;
    pNum = origIdx - 60 + 1;
  }
  const chId = `si-ma-fa_ch-${chNum}`;
  const pId = `${chId}_p-${pNum}`;
  return { chNum, pNum, chId, pId };
}

function cleanText(txt) {
  if (!txt) return '';
  return txt
    .replace(/古所謂/g, '古者')
    .replace(/如果/g, '若')
    .replace(/哪裡人/g, '安人')
    .replace(/誅殺處決/g, '誅')
    .replace(/去世/g, '卒')
    .replace(/也是/g, '亦')
    .replace(/因此明其/g, '是以明其')
    .replace(/因此/g, '是以')
    .replace(/遠所謂視/g, '遠者視')
    .replace(/不息也弊/g, '不息亦弊')
    .replace(/也反其懾/g, '亦反其懾');
}

const newPassages = [];
const newSentences = [];

oldSimaPassages.forEach((p, idx) => {
  const { chId, pId } = getNewIds(idx);
  newChaptersMap[chId].passageIds.push(pId);

  const oldSents = sentences.filter(s => s.passageId === p.id);
  const newSentIds = [];

  oldSents.forEach((s, sIdx) => {
    const sId = `${pId}_s-${sIdx + 1}`;
    newSentIds.push(sId);

    const cleanedCanonical = cleanText(s.canonicalText);
    const cleanedChunks = s.chunks ? s.chunks.map(chunk => [cleanText(chunk[0]), chunk[1]]) : undefined;

    newSentences.push({
      ...s,
      id: sId,
      passageId: pId,
      canonicalText: cleanedCanonical,
      chunks: cleanedChunks
    });
  });

  const cleanedPassageText = cleanText(p.originalText || p.text || p.content || '');

  newPassages.push({
    ...p,
    id: pId,
    chapterId: chId,
    sentenceIds: newSentIds,
    text: cleanedPassageText
  });
});

