  const ch = weiLiaoBundle.chapters.find(c => c.id === p.chapterId);
  const chNum = ch ? ch.order : Math.floor(idx / 2) + 1;
  const isP1 = idx % 2 === 0;
  
  const chData = weiLiaoChapters.find(c => c.ch === chNum);
