const entryPattern = /'(art-of-war_[^']+)'\s*:\s*\{\s*translation:\s*"((?:\\.|[^"\\])*)",\s*analysis:\s*"((?:\\.|[^"\\])*)"\s*\}/gs;
let replaced = 0;
source = source.replace(entryPattern, (whole, id, _oldTranslation, analysis) => {
  const translation = translations.get(id);
  if (!translation) return whole;
  replaced += 1;
  return `'${id}': {\n    translation: ${JSON.stringify(translation)},\n    analysis: "${analysis}"\n  }`;
});
if (replaced !== 70) throw new Error(`Expected to replace 70 entries, replaced ${replaced}`);
fs.writeFileSync(path, source, 'utf8');
console.log(`Corrected ${replaced} Sunzi translations.`);
