// OpenCC conversion for maximum traditional Chinese purity
function normalizeText(obj) {
  if (typeof obj === 'string') {
    return toTraditional(obj);
  }
  if (Array.isArray(obj)) {
    return obj.map(normalizeText);
  }
  if (typeof obj === 'object' && obj !== null) {
    const res = {};
    for (const key of Object.keys(obj)) {
      res[key] = normalizeText(obj[key]);
    }
    return res;
  }
  return obj;
}

