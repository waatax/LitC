const aidFile = path.join(root, 'src/data/readingAid.ts');
let aidSource = fs.readFileSync(aidFile, 'utf8');

let count = 0;
for (const [passageId, content] of Object.entries(daxueUpdates)) {
  const key = `'${passageId}':`;
  const formattedEntry = `  '${passageId}': {\n    translation: ${JSON.stringify(content.translation)},\n    analysis: ${JSON.stringify(content.analysis)}\n  },`;

  if (aidSource.includes(key)) {
    const pattern = new RegExp(`'${passageId}'\\s*:\\s*\\{[^\\}]+\\},?`, 's');
    aidSource = aidSource.replace(pattern, `'${passageId}': {\n    translation: ${JSON.stringify(content.translation)},\n    analysis: ${JSON.stringify(content.analysis)}\n  },`);
  } else {
    const lastBraceIndex = aidSource.lastIndexOf('}');
    aidSource = aidSource.slice(0, lastBraceIndex) + formattedEntry + '\n' + aidSource.slice(lastBraceIndex);
  }
  count++;
}

let written = false;
for (let attempt = 1; attempt <= 5; attempt++) {
  try {
    fs.writeFileSync(aidFile, aidSource, 'utf8');
    written = true;
    console.log(`Successfully fixed Daxue correct keys for ${count} passages!`);
    break;
  } catch (err) {
    console.log(`Attempt ${attempt} failed: ${err.message}. Retrying...`);
    const end = Date.now() + 500;
    while (Date.now() < end) {}
  }
}
